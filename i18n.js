  var ATTRS = ['data-title', 'data-desc', 'alt', 'aria-label', 'title', 'placeholder'];
  var originals = new WeakMap();   // nodo de texto → texto original
  var attrOriginals = new WeakMap(); // elemento → {attr: original}

  function store(k, v) { try { localStorage.setItem(k, v); } catch (e) {} }
  function load(k) { try { return localStorage.getItem(k); } catch (e) { return null; } }

  function tr(s, lang) {
    if (lang !== 'en') return s;
    var key = s.replace(/\s+/g, ' ').trim();
    var hit = EN[key];
    if (hit === undefined) return s;
    var lead = s.match(/^\s*/)[0], trail = s.match(/\s*$/)[0];
    return lead + hit + trail;
  }
  window.__t = function (s) { return tr(s, document.documentElement.lang === 'en' ? 'en' : 'es'); };

  function applyLang(lang) {
    document.documentElement.lang = lang;
    // Elementos con traducción completa en HTML (cuando el orden de las palabras cambia)
    document.querySelectorAll('[data-href-en]').forEach(function (el) {
      if (el.__esHref === undefined) el.__esHref = el.getAttribute('href');
      el.setAttribute('href', lang === 'en' ? el.getAttribute('data-href-en') : el.__esHref);
    });
    document.querySelectorAll('[data-en]').forEach(function (el) {
      if (el.__es === undefined) el.__es = el.innerHTML;
      el.innerHTML = lang === 'en' ? el.getAttribute('data-en') : el.__es;
    });
    var walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
      acceptNode: function (n) {
        var p = n.parentNode && n.parentNode.nodeName;
        return (p === 'SCRIPT' || p === 'STYLE') ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT;
      }
    });
    var n;
    while ((n = walker.nextNode())) {
      if (!n.nodeValue.trim()) continue;
      if (!originals.has(n)) originals.set(n, n.nodeValue);
      n.nodeValue = tr(originals.get(n), lang);
    }
    document.querySelectorAll('[' + ATTRS.join('],[') + ']').forEach(function (el) {
      var o = attrOriginals.get(el) || {};
      ATTRS.forEach(function (a) {
        if (!el.hasAttribute(a)) return;
        if (!(a in o)) o[a] = el.getAttribute(a);
        el.setAttribute(a, tr(o[a], lang));
      });
      attrOriginals.set(el, o);
    });
    if (!document.__origTitle) document.__origTitle = document.title;
    document.title = tr(document.__origTitle, lang);
    var btn = document.getElementById('lang-toggle');
    if (btn) btn.textContent = lang === 'en' ? 'ES' : 'EN';
  }

  function addToggles() {
    var inner = document.querySelector('#navbar .nav-inner');
    if (!inner || document.getElementById('site-toggles')) return;
    var wrap = document.createElement('div');
    wrap.id = 'site-toggles';
    wrap.className = 'site-toggles';
    wrap.innerHTML =
      '<button type="button" id="lang-toggle" class="toggle-btn" aria-label="Cambiar idioma" title="Cambiar idioma">EN</button>';
    var cta = inner.querySelector('.nav-cta');
    inner.insertBefore(wrap, cta || inner.querySelector('.hamburger'));

    document.getElementById('lang-toggle').addEventListener('click', function () {
      var next = document.documentElement.lang === 'en' ? 'es' : 'en';
      store('lang', next);
      applyLang(next);
    });
  }

  document.addEventListener('DOMContentLoaded', function () {
    addToggles();
    applyLang(load('lang') === 'en' ? 'en' : 'es');
  });
